#!/usr/bin/env node
/**
 * Writes each package's public API (entry points, exports, one-line summaries)
 * into its README between the API markers, from TypeDoc's JSON output.
 *
 * Usage:
 *   pnpm docs:build && node scripts/readme-api.mjs          # write
 *   pnpm docs:build && node scripts/readme-api.mjs --check  # fail if any README is stale
 *
 * npm renders only the README, so this is what puts the API on the npm page.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const SITE = 'https://brrritscold.github.io/ts-packages'
const START = '<!-- api:start -->'
const END = '<!-- api:end -->'

// TypeDoc ReflectionKind ids
const KIND = {
	2: 'module',
	4: 'namespace',
	8: 'enum',
	32: 'variable',
	64: 'function',
	128: 'class',
	256: 'interface',
	2097152: 'type',
	4194304: 'reference',
}

const check = process.argv.includes('--check')
const api = JSON.parse(readFileSync(join(ROOT, 'site/api.json'), 'utf8'))

/** First paragraph of a TypeDoc comment, flattened to one line. */
const summary = (reflection) => {
	const comment = reflection.comment ?? reflection.signatures?.[0]?.comment
	if (!comment?.summary) return ''
	const text = comment.summary
		// Fenced blocks are examples, not prose; inline `code` stays.
		.filter((part) => !(part.kind === 'code' && part.text.startsWith('```')))
		.map((part) => part.text)
		.join('')
		.split(/\n\s*\n/)[0]
		.replace(/\s+/g, ' ')
		.trim()
	return text.replace(/\|/g, '\\|')
}

/** TypeDoc's file name for a module page: `@brrritscold/core-node` + `query/mongodb` → `_brrritscold_core-node.query_mongodb`. */
const modulePage = (pkg, path = []) =>
	`${SITE}/modules/${[pkg.replace(/[@/]/g, '_'), ...path.map((p) => p.replace(/\//g, '_'))].join('.')}.html`

const table = (children) => {
	const rows = (children ?? [])
		.filter((c) => KIND[c.kind] && KIND[c.kind] !== 'reference')
		.sort((a, b) => a.name.localeCompare(b.name))
		.map((c) => `| \`${c.name}\` | ${KIND[c.kind]} | ${summary(c)} |`)
	if (!rows.length) return ''
	return ['| Export | Kind | Summary |', '| --- | --- | --- |', ...rows].join('\n')
}

const render = (pkg) => {
	const name = pkg.name
	const out = [
		START,
		'<!-- Generated by scripts/readme-api.mjs from the TSDoc comments. Do not edit by hand. -->',
		'',
		'## API',
		'',
		`Full reference: [${SITE.replace('https://', '')}](${modulePage(name)})`,
		'',
	]
	const entries = (pkg.children ?? []).filter((c) => c.kind === 2 || c.kind === 4)

	if (!entries.length) {
		// Single entry point: TypeDoc flattens the exports onto the package, so the
		// subpath comes from the package's exports map (packages have no root entry).
		const dir = name.replace('@brrritscold/', '')
		const { exports } = JSON.parse(
			readFileSync(join(ROOT, 'packages', dir, 'package.json'), 'utf8')
		)
		const [only] = Object.keys(exports)
		const importPath = `${name}/${only.replace(/^\.\//, '')}`
		out.push(
			`### \`${importPath}\``,
			'',
			'```ts',
			`import { … } from '${importPath}'`,
			'```',
			'',
			table(pkg.children),
			''
		)
	}
	for (const entry of entries) {
		const subpath = entry.kind === 2 // a module is its own subpath export
		const importLine = subpath
			? `import { … } from '${name}/${entry.name}'`
			: `import { ${entry.name} } from '${name}'`
		const heading = subpath ? `${name}/${entry.name}` : `${name} → ${entry.name}`
		out.push(`### [\`${heading}\`](${modulePage(name, [entry.name])})`, '')
		const about = summary(entry)
		if (about) out.push(about, '')
		out.push('```ts', importLine, '```', '')
		const body = table(entry.children)
		if (body) out.push(body, '')
	}
	out.push(END)
	return out.join('\n')
}

// Every public export needs a summary sentence: it is the README table row and the
// first line of the site page. An @example alone is not documentation.
const missing = []
const collect = (node, pkg) => {
	for (const c of node.children ?? []) {
		if (
			KIND[c.kind] &&
			!['module', 'namespace', 'reference'].includes(KIND[c.kind]) &&
			!summary(c)
		)
			missing.push(`${pkg}: ${c.name} (${c.sources?.[0]?.fileName ?? '?'})`)
		if (c.kind === 2 || c.kind === 4) collect(c, pkg)
	}
}
for (const pkg of api.children) collect(pkg, pkg.name)
if (check && missing.length) {
	console.error(`Exports without a TSDoc summary sentence:\n  ${missing.join('\n  ')}\n`)
}

let stale = 0
for (const pkg of api.children) {
	const dir = pkg.name.replace('@brrritscold/', '')
	const file = join(ROOT, 'packages', dir, 'README.md')
	const readme = readFileSync(file, 'utf8')
	const block = render(pkg)
	const s = readme.indexOf(START)
	const e = readme.indexOf(END)
	const next =
		s === -1 || e === -1
			? `${readme.trimEnd()}\n\n${block}\n`
			: `${readme.slice(0, s)}${block}${readme.slice(e + END.length)}`
	// Format as Biome would, so the generated file passes lint and --check is stable.
	const formatted = execFileSync(
		join(ROOT, 'node_modules/.bin/biome'),
		['format', `--stdin-file-path=${file}`],
		{
			input: next,
			encoding: 'utf8',
		}
	)
	if (formatted === readme) continue
	stale++
	if (check) console.error(`stale: packages/${dir}/README.md`)
	else {
		writeFileSync(file, formatted)
		console.log(`updated: packages/${dir}/README.md`)
	}
}

if (check && (stale || missing.length)) {
	if (stale) console.error('\nREADME API sections are out of date. Run: pnpm docs:readme')
	process.exit(1)
}
