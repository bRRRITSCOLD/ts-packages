import { writeFileSync } from 'node:fs'
import { parseArgs } from 'node:util'

import type { LibrarySnapshot } from '@brrritscold/design-core-js/library-snapshot'

import { createGitHubClient, type GitHubPullRequest } from './lib/github.js'
import { readLibrarySnapshot } from './library-snapshot.js'

export type { GitHubPullRequest }

/** Where the library snapshot lives in the repo, relative to its root. */
export const LIBRARY_SNAPSHOT_PATH = 'packages/core-react/design/library.snapshot.json'

/** The branch every refresh PR comes from; there is only ever one refresh PR. */
export const SNAPSHOT_REFRESH_BRANCH = 'design/snapshot-refresh'

/** The refresh PR's title, also its commit message. */
export const SNAPSHOT_REFRESH_TITLE = 'chore(core-react): refresh the library snapshot'

const PULL_REQUEST_BODY = `The nightly snapshot refresh read the design system library from Penpot and \`${LIBRARY_SNAPSHOT_PATH}\` changed.

- The drift check on this PR compares the library with \`core-react\`. A red drift check means a library edit broke the code: this PR never merges and gets the \`drift\` label.
- Generated by \`design-snapshot-refresh\` (\`@brrritscold/design-penpot-sdk-node\`). Don't push to this branch: the next refresh rebuilds it from the base branch.`

/** The defaults behind the optional environment variables of the snapshot refresh. */
export const SNAPSHOT_REFRESH_DEFAULTS = {
	SNAPSHOT_REFRESH_LIBRARY_FILE_ID: 'de716cff-f170-81a2-8008-e63b04772bf6',
	SNAPSHOT_REFRESH_GITHUB_REPO: 'bRRRITSCOLD/ts-packages',
	SNAPSHOT_REFRESH_BASE_BRANCH: 'main',
} as const

/** The snapshot refresh's configuration, as read by {@link readSnapshotRefreshConfig}. */
export type SnapshotRefreshConfig = {
	/** Penpot's URL; in the cluster, the frontend Service. */
	penpotUrl: string
	/** The automation profile's access token. */
	penpotToken: string
	/** The design system library file's id. */
	libraryFileId: string
	/** A PAT allowed to push the refresh branch and open PRs (a `GITHUB_TOKEN` PR wouldn't trigger CI). */
	githubToken: string
	/** `owner/name` of the repo holding the snapshot. */
	githubRepo: string
	/** The branch the snapshot is compared with and the PR targets. */
	baseBranch: string
}

/**
 * Reads the snapshot refresh's configuration from environment variables, throwing one error
 * that names every missing required variable.
 *
 * Required: `PENPOT_URL`, `SNAPSHOT_REFRESH_PENPOT_TOKEN` and, unless `githubToken` is
 * `'optional'` (writing the snapshot locally), `SNAPSHOT_REFRESH_GITHUB_TOKEN`. Optional, with
 * {@link SNAPSHOT_REFRESH_DEFAULTS}: `SNAPSHOT_REFRESH_LIBRARY_FILE_ID`,
 * `SNAPSHOT_REFRESH_GITHUB_REPO`, `SNAPSHOT_REFRESH_BASE_BRANCH`.
 *
 * @example
 * ```ts
 * // CJS
 * const { readSnapshotRefreshConfig } = require('@brrritscold/design-penpot-sdk-node/snapshot-refresh')
 * // ESM
 * import { readSnapshotRefreshConfig } from '@brrritscold/design-penpot-sdk-node/snapshot-refresh'
 *
 * readSnapshotRefreshConfig({ PENPOT_URL: 'https://penpot.example' })
 * // throws: Missing required environment variable(s): SNAPSHOT_REFRESH_PENPOT_TOKEN, SNAPSHOT_REFRESH_GITHUB_TOKEN
 * ```
 */
export const readSnapshotRefreshConfig = (
	env: Record<string, string | undefined>,
	{ githubToken = 'required' }: { githubToken?: 'required' | 'optional' } = {}
): SnapshotRefreshConfig => {
	const required = ['PENPOT_URL', 'SNAPSHOT_REFRESH_PENPOT_TOKEN']
	if (githubToken === 'required') required.push('SNAPSHOT_REFRESH_GITHUB_TOKEN')
	const missing = required.filter((name) => !env[name])
	if (missing.length)
		throw new Error(`Missing required environment variable(s): ${missing.join(', ')}`)

	const optional = (name: keyof typeof SNAPSHOT_REFRESH_DEFAULTS) =>
		env[name] || SNAPSHOT_REFRESH_DEFAULTS[name]
	return {
		penpotUrl: env.PENPOT_URL as string,
		penpotToken: env.SNAPSHOT_REFRESH_PENPOT_TOKEN as string,
		libraryFileId: optional('SNAPSHOT_REFRESH_LIBRARY_FILE_ID'),
		githubToken: env.SNAPSHOT_REFRESH_GITHUB_TOKEN ?? '',
		githubRepo: optional('SNAPSHOT_REFRESH_GITHUB_REPO'),
		baseBranch: optional('SNAPSHOT_REFRESH_BASE_BRANCH'),
	}
}

/**
 * Serializes a library snapshot the one way it is committed: tab-indented JSON with a trailing
 * newline. The normalizer already sorts it, so the same library always gives the same bytes.
 * Biome ignores the committed file, so a formatter never rewrites it into a false "changed".
 */
export const serializeLibrarySnapshot = (snapshot: LibrarySnapshot): string =>
	`${JSON.stringify(snapshot, null, '\t')}\n`

/**
 * What a refresh did: `unchanged` (the snapshot equals the base branch's, no PR), `up-to-date`
 * (the open refresh PR already holds it), `opened` or `updated` a refresh PR.
 */
export type SnapshotRefreshResult =
	| { outcome: 'unchanged' }
	| { outcome: 'up-to-date' | 'opened' | 'updated'; pullRequest: GitHubPullRequest }

/** What {@link refreshLibrarySnapshot} needs: the configuration, and optionally `fetch` and a logger. */
export type RefreshLibrarySnapshotParameters = SnapshotRefreshConfig & {
	/** The `fetch` both Penpot and GitHub are called with; defaults to the global one. */
	fetch?: typeof fetch
	/** Receives one line per decision; defaults to `console.log`. */
	log?: (line: string) => void
}

/**
 * Runs the snapshot refresh: reads the library snapshot from Penpot, compares it with
 * {@link LIBRARY_SNAPSHOT_PATH} on the base branch and, when it changed, commits it to
 * {@link SNAPSHOT_REFRESH_BRANCH} (rebuilt on top of the base branch) and opens a PR, or
 * updates the refresh PR already open. Unchanged does nothing.
 *
 * @example
 * ```ts
 * // CJS
 * const { readSnapshotRefreshConfig, refreshLibrarySnapshot } = require('@brrritscold/design-penpot-sdk-node/snapshot-refresh')
 * // ESM
 * import { readSnapshotRefreshConfig, refreshLibrarySnapshot } from '@brrritscold/design-penpot-sdk-node/snapshot-refresh'
 *
 * await refreshLibrarySnapshot(readSnapshotRefreshConfig(process.env))
 * // { outcome: 'opened', pullRequest: { number: 71, url: 'https://github.com/bRRRITSCOLD/ts-packages/pull/71' } }
 * ```
 */
export const refreshLibrarySnapshot = async ({
	fetch: fetchImpl = fetch,
	log = console.log,
	...config
}: RefreshLibrarySnapshotParameters): Promise<SnapshotRefreshResult> => {
	const { baseBranch: base, githubRepo: repo } = config
	const snapshot = serializeLibrarySnapshot(
		await readLibrarySnapshot({
			baseUrl: config.penpotUrl,
			accessToken: config.penpotToken,
			fileId: config.libraryFileId,
			fetch: fetchImpl,
		})
	)
	const github = createGitHubClient({ token: config.githubToken, repo, fetch: fetchImpl })

	if ((await github.readFile(LIBRARY_SNAPSHOT_PATH, base)) === snapshot) {
		log(`Library snapshot unchanged from ${repo}@${base}; no PR opened.`)
		return { outcome: 'unchanged' }
	}

	const open = await github.findOpenPullRequest(SNAPSHOT_REFRESH_BRANCH, base)
	if (
		open &&
		(await github.readFile(LIBRARY_SNAPSHOT_PATH, SNAPSHOT_REFRESH_BRANCH)) === snapshot
	) {
		log(`Library snapshot changed; refresh PR #${open.number} already holds it: ${open.url}`)
		return { outcome: 'up-to-date', pullRequest: open }
	}

	await github.commitFile({
		base,
		branch: SNAPSHOT_REFRESH_BRANCH,
		path: LIBRARY_SNAPSHOT_PATH,
		content: snapshot,
		message: SNAPSHOT_REFRESH_TITLE,
	})
	if (open) {
		log(`Library snapshot changed; updated refresh PR #${open.number}: ${open.url}`)
		return { outcome: 'updated', pullRequest: open }
	}
	const opened = await github.createPullRequest({
		branch: SNAPSHOT_REFRESH_BRANCH,
		base,
		title: SNAPSHOT_REFRESH_TITLE,
		body: PULL_REQUEST_BODY,
	})
	log(`Library snapshot changed; opened refresh PR #${opened.number}: ${opened.url}`)
	return { outcome: 'opened', pullRequest: opened }
}

/** What {@link runSnapshotRefreshCli} reads and writes; the process by default. */
export type SnapshotRefreshCliIo = {
	env: Record<string, string | undefined>
	stdout: (line: string) => void
	stderr: (line: string) => void
	writeFile: (path: string, content: string) => void
	fetch: typeof fetch
}

const processIo: SnapshotRefreshCliIo = {
	env: process.env,
	stdout: (line) => console.log(line),
	stderr: (line) => console.error(line),
	writeFile: (path, content) => writeFileSync(path, content),
	fetch: (...args) => fetch(...args),
}

/**
 * Runs the `design-snapshot-refresh` CLI and returns its exit code (0 done, 1 failed). With no
 * arguments it runs {@link refreshLibrarySnapshot} (the CronJob); with `--write <file>` it only
 * writes the snapshot to a local file, for committing into a `core-react` PR, and needs no
 * GitHub token.
 */
export const runSnapshotRefreshCli = async (
	argv: string[],
	io: SnapshotRefreshCliIo = processIo
): Promise<number> => {
	try {
		const { values } = parseArgs({
			args: argv,
			options: { write: { type: 'string' } },
			strict: true,
		})
		if (values.write !== undefined) {
			const config = readSnapshotRefreshConfig(io.env, { githubToken: 'optional' })
			const snapshot = await readLibrarySnapshot({
				baseUrl: config.penpotUrl,
				accessToken: config.penpotToken,
				fileId: config.libraryFileId,
				fetch: io.fetch,
			})
			io.writeFile(values.write, serializeLibrarySnapshot(snapshot))
			io.stdout(`Wrote the library snapshot to ${values.write}.`)
			return 0
		}
		await refreshLibrarySnapshot({
			...readSnapshotRefreshConfig(io.env),
			fetch: io.fetch,
			log: io.stdout,
		})
		return 0
	} catch (error) {
		io.stderr(`design-snapshot-refresh failed: ${(error as Error).message}`)
		return 1
	}
}
