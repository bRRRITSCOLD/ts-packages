// The last step of `build`: rewrites dist/icons.js so each icon is re-exported from its own
// lucide module (`lucide-react/icons/<file>`) instead of `export * from 'lucide-react'`.
//
// Why: Next's webpack barrel optimizer (`optimizePackageImports`) follows an `export *` into
// lucide's barrel file by absolute path, which loads every icon (~2000 modules) on a dev
// compile. With one re-export per icon file it loads only the icons an app imports.
// dist/icons.d.ts keeps tsc's `export * from 'lucide-react'`: the names are identical, which
// this script checks against lucide's own export list, failing the build on any difference.
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'

// Node resolves lucide's CJS build (the `node` condition); bundlers read its ESM barrel (`module`).
const resolved = fileURLToPath(import.meta.resolve('lucide-react'))
const packageDir = resolved.slice(0, resolved.lastIndexOf('/dist/') + 1)
const { module } = JSON.parse(await readFile(`${packageDir}package.json`, 'utf8')) as {
	module: string
}
const barrelUrl = pathToFileURL(`${packageDir}${module}`).href
const barrel = await readFile(new URL(barrelUrl), 'utf8')

/** `export { default as Trash, default as TrashIcon } from './icons/trash.mjs';` */
const ICON_LINE = /^export \{ ([^}]+) \} from '\.\/icons\/([a-z0-9-]+)\.mjs';$/gm

const lines: string[] = []
const exported = new Set<string>()
for (const [, specifiers, file] of barrel.matchAll(ICON_LINE)) {
	lines.push(`export { ${specifiers} } from 'lucide-react/icons/${file}'`)
	for (const s of specifiers.split(', ')) exported.add(s.replace(/^default as /, ''))
}

// Everything else lucide exports (`icons`, `Icon`, `createLucideIcon`, `LucideProvider`, …)
// comes from its root, which only loads when an app imports one of these.
const lucide = Object.keys(await import(barrelUrl))
const rest = lucide.filter((name) => !exported.has(name))
lines.push(`export { ${rest.join(', ')} } from 'lucide-react'`)

const extra = [...exported].filter((name) => !lucide.includes(name))
if (exported.size < 1000 || extra.length > 0) {
	throw new Error(
		`lucide-react's barrel format changed: parsed ${exported.size} icon exports, ${extra.length} not in its export list`
	)
}

const header =
	'// The `./icons` entry: every lucide icon. Apps import the `<Name>Icon` aliases (`TrashIcon`).\n// Generated by scripts/build-icons.ts: one re-export per icon module, so bundlers load only what is imported.\n'
await writeFile(new URL('../dist/icons.js', import.meta.url), `${header}${lines.join('\n')}\n`)
